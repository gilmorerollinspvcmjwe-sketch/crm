/** 获取报价单列表 */
export const getQuoteList = (filters?: {
  quoteNumber?: string;
  customerName?: string;
  status?: QuoteStatus;
  page?: number;
  pageSize?: number;
}) => {
  let filtered = [...quotes];
  
  if (filters?.quoteNumber) {
    filtered = filtered.filter(q => q.quoteNumber.includes(filters.quoteNumber!));
  }
  
  if (filters?.customerName) {
    filtered = filtered.filter(q => q.customerName.includes(filters.customerName!));
  }
  
  if (filters?.status) {
    filtered = filtered.filter(q => q.status === filters.status);
  }
  
  const total = filtered.length;
  const page = filters?.page || 1;
  const pageSize = filters?.pageSize || 20;
  const start = (page - 1) * pageSize;
  const list = filtered.slice(start, start + pageSize);
  
  return { list, total };
};

/** 获取报价单详情 */
export const getQuoteById = (id: string): Quote | undefined => {
  return quotes.find(q => q.id === id);
};

/** 获取报价统计 */
export const getQuoteStats = () => {
  const stats = {
    total: quotes.length,
    byStatus: {
      [QuoteStatus.DRAFT]: 0,
      [QuoteStatus.SENT]: 0,
      [QuoteStatus.ACCEPTED]: 0,
      [QuoteStatus.REJECTED]: 0,
      [QuoteStatus.EXPIRED]: 0,
    },
    totalAmount: 0,
    convertedCount: 0,
  };
  
  quotes.forEach(quote => {
    stats.byStatus[quote.status]++;
    stats.totalAmount += quote.grandTotal;
    if (quote.convertedToContractId) {
      stats.convertedCount++;
    }
  });
  
  return stats;
};
