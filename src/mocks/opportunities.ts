// ============ 辅助函数 ============

/**
 * 根据 ID 获取商机
 */
export function getOpportunityById(id: string): MockOpportunity | undefined {
  return mockOpportunities.find((o) => o.id === id)
}

/**
 * 获取所有商机
 */
export function getAllOpportunities(): MockOpportunity[] {
  return [...mockOpportunities]
}

/**
 * 根据阶段获取商机
 */
export function getOpportunitiesByStage(stage: OpportunityStage): MockOpportunity[] {
  return mockOpportunities.filter((o) => o.stage === stage)
}

/**
 * 根据优先级获取商机
 */
export function getOpportunitiesByPriority(priority: OpportunityPriority): MockOpportunity[] {
  return mockOpportunities.filter((o) => o.priority === priority)
}

/**
 * 根据客户 ID 获取商机
 */
export function getOpportunitiesByCustomerId(customerId: string): MockOpportunity[] {
  return mockOpportunities.filter((o) => o.customerId === customerId)
}

/**
 * 根据负责人获取商机
 */
export function getOpportunitiesByAssignee(assignee: string): MockOpportunity[] {
  return mockOpportunities.filter((o) => o.assignee === assignee)
}

/**
 * 获取活跃商机 (未成交/未失败)
 */
export function getActiveOpportunities(): MockOpportunity[] {
  return mockOpportunities.filter((o) => o.stage !== '成交' && o.stage !== '失败')
}

/**
 * 获取商机统计
 */
export function getOpportunityStats() {
  const total = mockOpportunities.length
  const won = mockOpportunities.filter((o) => o.stage === '成交').length
  const lost = mockOpportunities.filter((o) => o.stage === '失败').length
  const active = total - won - lost
  
  const totalAmount = mockOpportunities.reduce((sum, o) => sum + o.amount, 0)
  const wonAmount = mockOpportunities.filter((o) => o.stage === '成交').reduce((sum, o) => sum + o.amount, 0)
  const pipelineAmount = getActiveOpportunities().reduce((sum, o) => sum + o.amount, 0)
  
  const avgWinRate = mockOpportunities.reduce((sum, o) => sum + (o.winRate ?? 0), 0) / total
  
  return {
    total,
    won,
    lost,
    active,
    totalAmount,
    wonAmount,
    pipelineAmount,
    avgWinRate: Math.round(avgWinRate),
    winRate: total > 0 ? Math.round((won / (won + lost)) * 100) : 0,
  }
}

/**
 * 获取销售漏斗数据
 */
export function getSalesFunnel() {
  const stages: OpportunityStage[] = ['初步接触', '需求确认', '方案报价', '合同谈判', '成交', '失败']
  
  return stages.map(stage => {
    const opportunities = getOpportunitiesByStage(stage)
    const amount = opportunities.reduce((sum, o) => sum + o.amount, 0)
    return {
      stage,
      count: opportunities.length,
      amount,
      avgAmount: opportunities.length > 0 ? Math.round(amount / opportunities.length) : 0,
    }
  })
}
