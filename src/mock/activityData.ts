// 根据筛选条件过滤跟进记录
export const filterActivities = (
  activities: Activity[],
  filter: { relatedObjectType?: RelatedObjectType; type?: ActivityType; createdBy?: string }
): Activity[] => {
  return activities.filter(activity => {
    if (filter.relatedObjectType && activity.relatedObjectType !== filter.relatedObjectType) {
      return false;
    }
    if (filter.type && activity.type !== filter.type) {
      return false;
    }
    if (filter.createdBy && activity.createdByName !== filter.createdBy) {
      return false;
    }
    return true;
  });
};
