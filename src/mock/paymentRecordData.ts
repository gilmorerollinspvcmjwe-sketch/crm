/** 筛选回款记录 */
export function filterPaymentRecords(
  data: PaymentRecord[],
  filters: {
    contractName?: string
    customerName?: string
    reconciliationStatus?: string
    method?: string
    assignee?: string
  }
): PaymentRecord[] {
  return data.filter(record => {
    if (filters.contractName && !record.contractName?.includes(filters.contractName)) {
      return false
    }
    if (filters.customerName && !record.customerName?.includes(filters.customerName)) {
      return false
    }
    if (filters.reconciliationStatus && record.reconciliationStatus !== filters.reconciliationStatus) {
      return false
    }
    if (filters.method && record.method !== filters.method) {
      return false
    }
    if (filters.assignee && record.assignee !== filters.assignee) {
      return false
    }
    return true
  })
}
