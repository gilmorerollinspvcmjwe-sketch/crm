/** 获取联系人列表（支持筛选和分页） */
export const getContactList = (
  params: { 
    name?: string; 
    customerName?: string; 
    position?: string;
    page?: number; 
    pageSize?: number 
  } = {}
): { list: Contact[]; total: number } => {
  const { name = '', customerName = '', position = '', page = 1, pageSize = 20 } = params;
  
  let filtered = contactData.filter(item => {
    const matchName = !name || item.name.includes(name);
    const matchCustomer = !customerName || item.customerName?.includes(customerName);
    const matchPosition = !position || item.position?.includes(position);
    return matchName && matchCustomer && matchPosition;
  });

  const total = filtered.length;
  const start = (page - 1) * pageSize;
  const end = start + pageSize;
  const list = filtered.slice(start, end);

  return { list, total };
};

/** 根据 ID 获取联系人详情 */
export const getContactById = (id: string): Contact | undefined => {
  return contactData.find(item => item.id === id);
};

/** 根据客户 ID 获取联系人列表 */
export const getContactsByCustomerId = (customerId: string): Contact[] => {
  return contactData.filter(item => item.customerId === customerId);
};
