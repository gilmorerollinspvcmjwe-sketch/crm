/** 报价产品明细生成器 */
const generateQuoteProducts = (count: number): QuoteProduct[] => {
  const result: QuoteProduct[] = [];
  for (let i = 0; i < count; i++) {
    const product = products[Math.floor(Math.random() * products.length)];
    const quantity = Math.floor(Math.random() * 10) + 1;
    const discount = Math.floor(Math.random() * 20); // 0-20% 折扣
    const subtotal = product.unitPrice * quantity;
    const tax = subtotal * 0.13; // 13% 增值税
    const total = subtotal * (1 - discount / 100) + tax;
    
    result.push({
      id: `QP${Date.now()}${i}`,
      productId: product.id,
      productName: product.name,
      quantity,
      unitPrice: product.unitPrice,
      discount,
      subtotal,
      tax: Math.round(tax),
      total: Math.round(total),
    });
  }
  return result;
};

/** 计算报价单总计 */
const calculateTotals = (quoteProducts: QuoteProduct[]) => {
  const subtotal = quoteProducts.reduce((sum, p) => sum + p.subtotal, 0);
  const totalDiscount = quoteProducts.reduce((sum, p) => sum + (p.subtotal * p.discount / 100), 0);
  const totalTax = quoteProducts.reduce((sum, p) => sum + p.tax, 0);
  const grandTotal = quoteProducts.reduce((sum, p) => sum + p.total, 0);
  
  return {
    subtotal: Math.round(subtotal),
    totalDiscount: Math.round(totalDiscount),
    totalTax: Math.round(totalTax),
    grandTotal: Math.round(grandTotal),
  };
};

